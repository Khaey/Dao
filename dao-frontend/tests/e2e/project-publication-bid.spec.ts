  const artisanCheckContext = await browser.newContext();
  const artisanCheck = await artisanCheckContext.newPage();
  await login(artisanCheck, e2eArtisan!);
  await artisanCheck.goto(`/app/artisan/publications/${publicationId}`);
  await expect(artisanCheck.getByText('Non retenue', { exact: true })).toBeVisible();
