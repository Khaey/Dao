import { readFileSync, writeFileSync } from 'node:fs';
import { assertCatalogConsistent, SETTINGS_CATALOG_VERSION } from './catalog.js';
import { catalogHash, catalogSqlLiteral } from './projection.js';

// Writes the generated catalogue block into a settings migration:
//   npm run settings:sync -- supabase/migrations/<file>.sql
// A new catalogue version must go into a NEW migration (applied ones are immutable).
export function catalogBlock(): string {
  return `-- settings-catalog:begin (generated by \`npm run settings:sync\`, do not edit)\n`
    + `select dao_private.sync_setting_definitions(${SETTINGS_CATALOG_VERSION}, '${catalogHash()}', '${catalogSqlLiteral()}'::jsonb);\n`
    + `-- settings-catalog:end`;
}

export const CATALOG_BLOCK = /-- settings-catalog:begin[^\n]*\n[\s\S]*?\n-- settings-catalog:end/;

if (process.argv[1]?.endsWith('sync-migration.ts') || process.argv[1]?.endsWith('sync-migration.js')) {
  const file = process.argv[2];
  if (!file) throw new Error('usage: settings:sync -- <migration.sql>');
  assertCatalogConsistent();
  const sql = readFileSync(file, 'utf8');
  if (!CATALOG_BLOCK.test(sql)) throw new Error('settings-catalog block not found');
  writeFileSync(file, sql.replace(CATALOG_BLOCK, catalogBlock()));
}
